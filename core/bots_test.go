// When the player finishes, each bot finishes its replay delay later, so the race can end.
func TestBotsFinishAfterReference(t *testing.T) {
	setupRoom(t, DefaultConfig())
	human := addTestAid(t, 0, false)
	addTestBots(t, 1, 3)

	// Player ids: human 0, bots 1-3.
	info := raceInfo(common.LuigiCircuit, 100)
	for id, aid := range []byte{0, 1, 2, 3} {
		info[0x18+id] = aid
	}

	send := func(finished bool, at time.Time) {
		b := &packetBuilder{sender: 0, dests: 0xe}
		b.recs[recRaceInfo] = info
		rm := vsRaceModeRec(0)
		if finished {
			records.PutBits(rm, 0, 13, 1<<12)            // Bit for player id 0.
			records.PutBits(rm, 45, 22, 1<<16|5<<10|900) // 1:05.900
		}
		b.recs[recRaceMode] = rm
		b.recs[recRaceData] = raceData(1)
		handle(human, b.build(), at)
	}

	start := time.Now()
	send(false, start)
	send(true, start.Add(time.Second))

	finishes := func(at time.Time) map[byte]*records.RaceModeVS {
		mu.Lock()
		defer mu.Unlock()
		out := map[byte]*records.RaceModeVS{}
		for _, o := range botPackets(at) {
			rm, err := records.ParseRaceMode(o.data[records.HeaderLen+records.RaceInfoLen:][:records.RaceModeLen], &records.Context{SenderAid: o.data[1], LocalPlayerCount: 1}, common.ModeVS, true)
			if err != nil {
				t.Fatal(err)
			}
			out[o.data[1]] = rm.VS
		}
		return out
	}

	// 0.5s after the player: only bot 1 (0.4s delay) has finished.
	vs := finishes(start.Add(1500 * time.Millisecond))
	if ft := vs[1].FinishTimes[0]; ft.Minutes != 1 || ft.Seconds != 6 || ft.Milliseconds != 300 {
		t.Fatalf("bot 1 finish time %+v, want 1:06.300", ft)
	}
	if vs[1].FinishedPlayers != 1<<12|1<<11 {
		t.Fatalf("bot 1 finished field %013b, want player 0 and 1", vs[1].FinishedPlayers)
	}
	if ft := vs[2].FinishTimes[0]; ft != (records.FinishTime{}) {
		t.Fatalf("bot 2 finished early: %+v", ft)
	}

	// Later, every bot has finished.
	for aid, v := range finishes(start.Add(3 * time.Second)) {
		if v.FinishTimes[0] == (records.FinishTime{}) {
			t.Fatalf("bot %d never finished", aid)
		}
	}

	// A new race clears it.
	send(false, start.Add(10*time.Second))
	if ft := finishes(start.Add(11 * time.Second))[3].FinishTimes[0]; ft != (records.FinishTime{}) {
		t.Fatalf("bot finish carried into the next race: %+v", ft)
	}
}

func TestMirrorKeepsRecordsOverLoneEmptyPacket(t *testing.T) {
	a := &Aid{raceStarted: true}
	m := &mirrorSource{}
	a.mirror = m
	now := time.Now()
	m.records[common.RaceInfo] = []byte{1}
	m.lastFullAt = now
	empty := encodeRacePacket(0, 1, [numRecordTypes][]byte{})
	h, err := records.ParseHeader(append([]byte{}, empty...))
	if err != nil {
		t.Fatal(err)
	}
	pkt := &RacePacket{Header: h}
	recordMirrorSource(a, empty, pkt, now.Add(16*time.Millisecond))
	if m.records[common.RaceInfo] == nil {
		t.Fatal("lone empty packet wiped the mirrored RACEHEADER_1")
	}
	recordMirrorSource(a, empty, pkt, now.Add(time.Second))
	if m.records[common.RaceInfo] != nil {
		t.Fatal("a run of empty packets kept stale records")
	}
}

func TestBotsAcknowledgeItems(t *testing.T) {
	ref := &Aid{aid: 0, mirror: &mirrorSource{}}
	ref.mirror.records[common.Item] = []byte{0x2a, byte(common.Banana), byte(common.NoItem), 1, 0, 0, 0, 0}
	ref.mirror.itemTimer = 0x2a
	bot := &Aid{aid: 1, bot: newBotState(1)}
	data := buildBotPacket(bot, ref, ref, time.Now())
	h, err := records.ParseHeader(append([]byte{}, data...))
	if err != nil {
		t.Fatal(err)
	}
	if h.ItemLen() != records.ItemLen {
		t.Fatalf("bot sent no ITEM record")
	}
	if item := data[len(data)-records.ItemLen:]; item[6] != 0x2a {
		t.Fatalf("bot ack_timer %#x, want 0x2a", item[6])
	}
}
