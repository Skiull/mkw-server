// Bot packets are generated by the server, so hold them to the same validation real
// clients get. A bot packet that fails here would likely confuse the game too.
func TestBotPacketsPassValidation(t *testing.T) {
	setupRoom(t, DefaultConfig())
	human := addTestAid(t, 0, false)
	addTestBots(t, 1, 11)

	now := time.Now()
	for i := range 50 {
		b := &packetBuilder{sender: 0, dests: 0xffe}
		b.recs[recRaceInfo] = raceInfo(common.LuigiCircuit, 100)
		b.recs[recRaceMode] = vsRaceModeRec(0)
		b.recs[recRoomSelect] = selectRec()
		b.recs[recRaceData] = raceData(byte(1 + i%12))
		b.recs[recUser] = userRec(600000123)
		b.recs[recItem] = itemRec(common.NoItem, common.NoItem)
		b.recs[recEvent] = eventRec()
		if to := handle(human, b.build(), now.Add(time.Duration(i)*100*time.Millisecond)); len(to) != 0 {
			t.Fatalf("packet addressed to bots was relayed to %v", to)
		}
	}

	mu.Lock()
	out := botPackets(now.Add(5 * time.Second))
	mu.Unlock()
	if len(out) != 11 {
		t.Fatalf("got %d bot packets, want 11", len(out))
	}

	seenFC := map[uint64]bool{}
	for _, o := range out {
		if o.to.String() != human.addr.String() {
			t.Fatalf("bot packet sent to %v", o.to)
		}
		botAid := o.data[1]
		mu.Lock()
		ctx := getAid(botAid).context()
		mu.Unlock()
		ctx.SenderAid = botAid

		pkt, err := parseRacePacket(o.data, ctx)
		if err != nil {
			t.Fatalf("bot %d packet invalid: %v", botAid, err)
		}
		if pkt.Destinations != 1<<0 {
			t.Fatalf("bot %d addressed %#x", botAid, pkt.Destinations)
		}
		if pkt.RaceMode.VS.Slots[0] != botAid {
			t.Fatalf("bot %d reports slot %d", botAid, pkt.RaceMode.VS.Slots[0])
		}
		if seenFC[pkt.User.FriendCode] {
			t.Fatalf("duplicate bot friend code %d", pkt.User.FriendCode)
		}
		seenFC[pkt.User.FriendCode] = true
		if !records.IsValidFriendCode(pkt.User.FriendCode, "RMCJ") {
			t.Fatalf("bot %d friend code %d isn't valid for RMCJ, which the game requires", botAid, pkt.User.FriendCode)
		}
		if got := binary.BigEndian.Uint64(o.data[records.HeaderLen+records.RaceInfoLen+records.RaceModeLen+8:]); got < 123456 {
			t.Fatalf("bot %d time_receiver %d doesn't echo the player's clock", botAid, got)
		}
	}
}

// Bots trail the reference: each replays RaceData from further back.
func TestBotsReplayDelayedRaceData(t *testing.T) {
	setupRoom(t, DefaultConfig())
	human := addTestAid(t, 0, false)
	addTestBots(t, 1, 3)

	start := time.Now()
	for i := range 40 {
		b := racingPacket(0, 1<<1, byte(1+i%12))
		handle(human, b.build(), start.Add(time.Duration(i)*100*time.Millisecond))
	}

	now := start.Add(4 * time.Second)
	mu.Lock()
	defer mu.Unlock()
	ranks := map[byte]byte{}
	for _, o := range botPackets(now) {
		rd, err := records.ParseRaceData(o.data[records.HeaderLen+records.RaceInfoLen:][:records.RaceDataLen])
		if err != nil {
			t.Fatal(err)
		}
		ranks[o.data[1]] = rd.Rank
	}
	// Packet i carries rank 1+i%12 and arrives at i*100ms. Bot n replays n*400ms ago.
	for bot, want := range map[byte]byte{1: 1 + 36%12, 2: 1 + 32%12, 3: 1 + 28%12} {
		if ranks[bot] != want {
			t.Fatalf("bot %d replayed rank %d, want %d (all: %v)", bot, ranks[bot], want, ranks)
		}
	}
}

