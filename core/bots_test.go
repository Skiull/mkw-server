func selectRec() []byte {
	d := make([]byte, records.SelectLen)
	d[0x14], d[0x15], d[0x16] = byte(common.Mario), byte(common.StandardKartM), byte(common.LuigiCircuit)
	d[0x1c], d[0x1d], d[0x1e] = byte(common.SelectDefaultCharacter), byte(common.SelectDefaultVehicle), byte(common.Random)
	for i := range 12 {
		d[0x28+i] = records.NoAid
	}
	d[0x34], d[0x36] = byte(common.NoVote), records.NoAid
	binary.BigEndian.PutUint64(d[0:], 123456)
	return d
}

func vsRaceModeRec(aid byte) []byte {
	d := make([]byte, records.RaceModeLen)
	records.PutBits(d, 39, 2, 1)
	records.PutBits(d, 41, 4, uint32(aid))
	return d
}

