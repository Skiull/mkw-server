// Test bots: fake players wfc-server adds to a room so one person can test a full room.
//
// Bots don't run any game logic. Each bot mirrors the packets of a real player in the room
// (the "reference"): it copies their race state (lobby phase, course, countdown, etc.) and
// substitutes its own aid, character, vehicle and friend code. Its RaceData is the
// reference's RaceData from a few seconds ago, so bots trail along the reference's line.
//
// Bot packets are generated by the server and sent straight to real players. They never go
// through validation, and packets addressed to bots are consumed instead of relayed.

// How often bots send a packet to each real player.
const botSendInterval = 33 * time.Millisecond

// How much RaceData history is kept for bots to replay.
const botHistory = 8 * time.Second

// Bots stop sending if the reference hasn't sent anything for this long.
const botReferenceTimeout = 2 * time.Second

// Bot profile ids start here, so bot friend codes are valid and don't collide with players.
const botProfileIdBase = 0x7f000000

// How long after a packet with records a record-less one is ignored.
const botEmptyPacketGrace = 200 * time.Millisecond

// Index of each record's length in the Header, matching common.RecordIdx.
const numRecordTypes = 8

type botState struct {
	// Characters and vehicles by weight class: index 0 small, 1 medium, 2 large.
	character    common.Character
	vehicleClass int
	// How far behind the reference the bot replays RaceData.
	delay time.Duration
	// AI driving (ai_bots.go), when --ai-bots is set.
	ai *aiBotState
}

// timedRecord is a RaceData record from the reference and when it arrived.
type timedRecord struct {
	at   time.Time
	data []byte
}

// mirrorSource is what the server remembers about a real player so bots can mirror it.
type mirrorSource struct {
	records    [numRecordTypes][]byte // Latest raw record of each type.
	lastAt     time.Time
	lastFullAt time.Time // Last packet that held any records.
	itemTimer  byte      // Timer of player 1's latest ITEM record, for bots to acknowledge.
	raceData   []timedRecord
	timeSender uint64 // Latest Select time_sender, echoed back as time_receiver.
	lastUser   []byte // Latest User record (Miis, names, location), kept across packets.
	lastSelect []byte // Latest Select record (room phase, course, player map), likewise.
	timeAt     time.Time

	// When the reference finished the current race (zero until then), their finishing time,
	// and where their bit sits in RaceMode's finished-players field relative to their player
	// id. Bots finish their replay delay after the reference.
	finishedAt     time.Time
	finishTime     records.FinishTime
	finishBitShift int
}

var botCharacters = [3][]common.Character{
	{common.BabyMario, common.BabyLuigi, common.BabyPeach, common.BabyDaisy, common.Toad, common.Toadette, common.KoopaTroopa, common.DryBones},
	{common.Mario, common.Luigi, common.Peach, common.Daisy, common.Yoshi, common.Birdo, common.DiddyKong, common.BowserJr},
	{common.Wario, common.Waluigi, common.DonkeyKong, common.Bowser, common.KingBoo, common.Rosalina, common.FunkyKong, common.DryBowser},
}

func newBotState(aid byte) *botState {
	class := int(aid) % 3
	chars := botCharacters[class]
	return &botState{
		character:    chars[int(aid)/3%len(chars)],
		vehicleClass: class,
		delay:        time.Duration(aid) * 400 * time.Millisecond,
	}
}

// vehicle picks a vehicle of the bot's weight class. Vehicle ids cycle small, medium,
// large, and ids from 18 up are bikes. Bots match the reference's karts-or-bikes choice so
// they respect the room's vehicle rules.
func (b *botState) vehicle(referenceVehicle byte) common.Vehicle {
	base := 0 // Standard Kart
	if referenceVehicle >= byte(common.StandardBikeS) && referenceVehicle <= byte(common.Phantom) {
		base = int(common.StandardBikeS)
	}
	return common.Vehicle(base + b.vehicleClass)
}

// Mario Kart Wii always makes friend codes with the RMCJ game id, whatever the disc's region,
// and the WiiLink payload rejects USER records whose friend code isn't valid for RMCJ.
func botFriendCode(aid byte) uint64 {
	return records.CalcFriendCode(botProfileIdBase+uint32(aid), "RMCJ")
}

// AddBotToRoom adds a test bot. addr is only an identifier so wfc-server can remove the bot
// later; nothing is sent to it.
func AddBotToRoom(botAddr string, aid byte) error {
	mu.Lock()
	defer mu.Unlock()

	if _, exists := aids[botAddr]; exists {
		return fmt.Errorf("Bot %s already exists in room", botAddr)
	}
	if getAid(aid) != nil {
		return fmt.Errorf("Aid number %d is already in use", aid)
	}

	a, err := NewAid(botAddr, aid, false, false)
	if err != nil {
		return fmt.Errorf("Failed to create bot %s: %w", botAddr, err)
	}
	a.bot = newBotState(aid)

	aids[botAddr] = a
	logging.Log("Added test bot aid %d. Aid count is %d", aid, len(aids))
	return nil
}

// recordMirrorSource remembers a real player's packet for bots to mirror.
// Caller must hold mu.
func recordMirrorSource(a *Aid, data []byte, pkt *RacePacket, now time.Time) {
	if a.mirror == nil {
		a.mirror = &mirrorSource{}
	}
	m := a.mirror

	h := pkt.Header
	lengths := [numRecordTypes]byte{records.HeaderLen, h.RaceInfoLen(), h.RaceModeLen(), h.RoomSelectLen(), h.RaceDataLen(), h.UserLen(), h.ItemLen(), h.EventLen()}
	// A lone record-less packet mid-race (the client sends one now and then) would leave the
	// bots without a RACEHEADER_1 timer until the next packet; the game disconnects when a
	// peer's timer looks off. Keep the last records unless these packets keep coming (the
	// results screen sends nothing else).
	empty := true
	for _, n := range lengths[1:] {
		empty = empty && n == 0
	}
	if empty && a.raceStarted && now.Sub(m.lastFullAt) < botEmptyPacketGrace {
		return
	}
	if !empty {
		m.lastFullAt = now
	}
	offset := 0
	// Bots send exactly the record types the reference just sent. Leftover race records sent
	// with a vote-screen Select get the bots kicked as malicious.
	for i, n := range lengths {
		if i > 0 {
			m.records[i] = nil
			if n != 0 {
				m.records[i] = append([]byte{}, data[offset:offset+int(n)]...)
			}
		}
		offset += int(n)
	}
	// Room records are friend room actions (start, chat). Bots never repeat those.
	if pkt.Room != nil {
		m.records[common.RoomSelect] = nil
	}
	m.lastAt = now
	if u := m.records[common.User]; u != nil {
		m.lastUser = u
	}
	if sel := m.records[common.RoomSelect]; len(sel) == records.SelectLen {
		m.lastSelect = sel
	}
	if it := m.records[common.Item]; len(it) >= records.ItemLen {
		m.itemTimer = it[0]
	}
	trackReferenceFinish(m, a.aid, pkt, now)

	if len(pkt.RaceData) > 0 {
		m.raceData = append(m.raceData, timedRecord{at: now, data: m.records[common.RaceData][:records.RaceDataLen]})
		cut := 0
		for cut < len(m.raceData) && now.Sub(m.raceData[cut].at) > botHistory {
			cut++
		}
		m.raceData = m.raceData[cut:]
	}

	if pkt.Select != nil {
		m.timeSender = binary.BigEndian.Uint64(data[selectOffset(pkt):])
		m.timeAt = now
	}
}

func selectOffset(pkt *RacePacket) int {
	h := pkt.Header
	return records.HeaderLen + int(h.RaceInfoLen()) + int(h.RaceModeLen())
}

// botReference picks the real player bots mirror: the lowest aid that's sending packets.
// Caller must hold mu.
func botReference(now time.Time) *Aid {
	var ref *Aid
	for _, a := range aids {
		if a.bot != nil || a.kicked || a.mirror == nil || now.Sub(a.mirror.lastAt) > botReferenceTimeout {
			continue
		}
		if ref == nil || a.aid < ref.aid {
			ref = a
		}
	}
	return ref
}

type outgoing struct {
	to   net.Addr
	data []byte
}

func botLoop() {
	ticker := time.NewTicker(botSendInterval)
	defer ticker.Stop()
	for now := range ticker.C {
		mu.Lock()
		out := botPackets(now)
		mu.Unlock()

		for _, o := range out {
			if _, err := room.conn.WriteTo(o.data, o.to); err != nil {
				logging.Log("Error sending bot packet to %v: %v", o.to, err)
			}
		}
	}
}

// botPackets builds one packet from every bot to every real player. Caller must hold mu.
func botPackets(now time.Time) []outgoing {
	if replay != nil && room.config.ReplaySpectate {
		return replayPackets(now)
	}
	ref := botReference(now)
	if ref == nil {
		return nil
	}

	var out []outgoing
	for _, bot := range aids {
		if bot.bot == nil {
			continue
		}
		if room.config.CheckMovement && ref.mirror != nil && len(bot.players) > 0 {
			if data := botRaceData(ref.mirror, bot.bot.delay, now); data != nil {
				if rd, err := records.ParseRaceData(data[:records.RaceDataLen]); err == nil {
					trackProgress(bot, 0, rd, ref.course, 0, now)
				}
			}
		}
		for _, dest := range aids {
			if dest.bot != nil || dest.kicked {
				continue
			}
			out = append(out, outgoing{to: dest.addr, data: buildBotPacket(bot, ref, dest, now)})
			bot.stats.sent++
		}
	}
	return out
}

// buildBotPacket makes a Race packet from a bot to dest by mirroring ref.
func buildBotPacket(bot, ref, dest *Aid, now time.Time) []byte {
	src := &ref.mirror.records
	var recs [numRecordTypes][]byte

	refVehicle := byte(common.RaceInfoDefaultVehicle)
	mode := common.ModeUnknown
	if ri := src[common.RaceInfo]; ri != nil {
		refVehicle = ri[0xe]
		if info, err := records.ParseRaceInfo(ri); err == nil {
			mode = info.GameMode()
		}
	}
	vehicle := bot.bot.vehicle(refVehicle)
	rp := replayPlayerFor(bot)
	if rp != nil {
		vehicle = rp.vehicle
	}
	character := bot.bot.character
	if rp != nil {
		character = rp.character
	}
	if room.config.AIBotDir != "" && rp == nil {
		if bot.bot.ai == nil {
			bot.bot.ai = &aiBotState{}
			bot.bot.ai.character, bot.bot.ai.vehicle = newAIBotCombo(bot.aid)
		}
		character, vehicle = common.Character(bot.bot.ai.character), common.Vehicle(bot.bot.ai.vehicle)
	}

	if ri := src[common.RaceInfo]; ri != nil {
		d := append([]byte{}, ri...)
		binary.BigEndian.PutUint16(d[0xc:], 0) // No lag.
		if d[0xe] != byte(common.RaceInfoDefaultVehicle) {
			d[0xe], d[0xf] = byte(vehicle), byte(character)
		}
		d[0x10], d[0x11] = byte(common.RaceInfoDefaultVehicle), byte(common.RaceInfoDefaultCharacter)
		recs[common.RaceInfo] = d
	}

	if rm := src[common.RaceMode]; rm != nil {
		recs[common.RaceMode] = botRaceMode(rm, mode, bot, ref, rp, now)
	}

	if sel := src[common.RoomSelect]; len(sel) == records.SelectLen {
		recs[common.RoomSelect] = botSelect(sel, bot, vehicle, character, dest, now)
		if rp != nil && replay.course.IsValid(common.RoomSelect) {
			recs[common.RoomSelect][0x16] = byte(replay.course) // Vote for the recorded course.
		}
	}

	if rd := src[common.RaceData]; rd != nil {
		recs[common.RaceData] = botRaceData(ref.mirror, bot.bot.delay, now)
		if rp == nil {
			if d := aiBotRaceData(bot, ref, now); d != nil {
				// Same record length as the reference's (two players' worth with a guest).
				if len(rd) > len(d) {
					d = append(d, make([]byte, len(rd)-len(d))...)
				}
				recs[common.RaceData] = d
			}
		}
		if rp != nil {
			if d := rp.replayRaceData(replayMs(ref, now)); d != nil {
				recs[common.RaceData] = d
			}
		}
	}

	if u := src[common.User]; u != nil {
		d := append([]byte{}, u...)
		binary.BigEndian.PutUint32(d[0x0:], 1) // Only player 1's Mii.
		binary.BigEndian.PutUint64(d[0xa8:], botFriendCode(bot.aid))
		recs[common.User] = d
	}

	if src[common.Item] != nil {
		// No item of their own, but accept dest's item: ack_timer echoes the timer of the
		// other client's item. Without it, dest's game never sees its item accepted and
		// eventually disconnects (seen right after item grants with 11 bots).
		var ack byte
		if dest.mirror != nil {
			ack = dest.mirror.itemTimer
		}
		recs[common.Item] = []byte{0, byte(common.NoItem), byte(common.NoItem), 0, 0, 0, ack, 0}
	}

	if src[common.Event] != nil {
		d := make([]byte, records.EventSlotCount)
		for i := range d {
			d[i] = byte(common.ObjNone)
		}
		recs[common.Event] = d
	}

	recordBotPacket(bot, recs, now)
	return encodeRacePacket(bot.aid, dest.aid, recs)
}

func botRaceMode(rm []byte, mode common.GameMode, bot *Aid, ref *Aid, rp *replayPlayer, now time.Time) []byte {
	m := ref.mirror
	d := append([]byte{}, rm...)
	aid := bot.aid
	switch mode {
	case common.ModeVS:
		records.PutBits(d, 39, 2, 1)           // One local player.
		records.PutBits(d, 41, 4, uint32(aid)) // Player 1 slot.
		records.PutBits(d, 45, 22, 0)          // Not finished.
		ft, bit, ok := botFinish(bot, m, now)
		if rp == nil && bot.bot.ai != nil && bot.bot.ai.driver != nil {
			ft, ok = aiBotFinish(bot)
			bit = -1
			if id := playerIdOf(m.records[common.RaceInfo], bot.aid); id >= 0 {
				bit = id + m.finishBitShift
			}
		}
		if rp != nil {
			// Replayed racers finish at their recorded time.
			ft, ok = rp.replayFinished(replayMs(ref, now))
			bit = -1
			if id := playerIdOf(m.records[common.RaceInfo], bot.aid); id >= 0 {
				bit = id + m.finishBitShift
			}
		}
		if ok {
			raceHadFinisher = true // Bots finishing first end the race for everyone too.
			records.PutBits(d, 45, 22, packFinishTime(ft))
			if bit >= 0 && bit < raceModePlayerBits {
				records.PutBits(d, bit, 1, 1)
			}
		}
		records.PutBits(d, 67, 13, 0)
		records.PutBits(d, 80, 4, 0) // No player 2.
		records.PutBits(d, 84, 22, 0)
		records.PutBits(d, 106, 13, 0)
		d[0x1c] = 0 // Not disconnected.
		clear(d[0x1e:0x26])
	case common.ModeBalloonBattle:
		d[0] = aid<<4 | 0xc
		records.PutBits(d, 8, 14, 0) // Scores.
	}
	return d
}

func botSelect(sel []byte, bot *Aid, vehicle common.Vehicle, character common.Character, dest *Aid, now time.Time) []byte {
	d := append([]byte{}, sel...)

	// time_sender is milliseconds since 2000-01-01. time_receiver echoes dest's clock.
	epoch := time.Date(2000, 1, 1, 0, 0, 0, 0, time.UTC)
	binary.BigEndian.PutUint64(d[0x0:], uint64(now.Sub(epoch).Milliseconds()))
	var receiver uint64
	if m := dest.mirror; m != nil && m.timeSender != 0 {
		receiver = m.timeSender + uint64(now.Sub(m.timeAt).Milliseconds())
	}
	binary.BigEndian.PutUint64(d[0x8:], receiver)

	// Player 1 keeps the reference's spot, points, vote and rank icon.
	d[0x14], d[0x15] = byte(character), byte(vehicle)

	// No guest.
	clear(d[0x18:0x1c])
	d[0x1c], d[0x1d], d[0x1e], d[0x1f] = byte(common.SelectDefaultCharacter), byte(common.SelectDefaultVehicle), byte(common.Random), 0
	return d
}

// botRaceData replays the reference's RaceData from delay ago.
func botRaceData(m *mirrorSource, delay time.Duration, now time.Time) []byte {
	if len(m.raceData) == 0 {
		return nil
	}
	pick := m.raceData[0]
	target := now.Add(-delay)
	for _, r := range m.raceData {
		if r.at.After(target) {
			break
		}
		pick = r
	}
	return append([]byte{}, pick.data...)
}

// encodeRacePacket lays out records behind a Header and fills in the checksum. Records
// that are nil are left out.
func encodeRacePacket(sender, dest byte, recs [numRecordTypes][]byte) []byte {
	data := make([]byte, records.HeaderLen)
	data[0] = RacePacketMagic
	data[1] = sender
	binary.BigEndian.PutUint16(data[2:4], 1<<dest)
	data[8] = records.HeaderLen
	for i := 1; i < numRecordTypes; i++ {
		data[8+i] = byte(len(recs[i]))
		data = append(data, recs[i]...)
	}
	binary.BigEndian.PutUint32(data[4:8], crc32.ChecksumIEEE(data))
	return data
}

// RaceMode's player bitfields are 13 bits: one per player id plus one.
const raceModePlayerBits = 13

// playerIdOf returns the player id an aid has in a RaceInfo's player id -> aid map.
func playerIdOf(raceInfo []byte, aid byte) int {
	if len(raceInfo) < 0x24 {
		return -1
	}
	for id, a := range raceInfo[0x18:0x24] {
		if a == aid {
			return id
		}
	}
	return -1
}

// trackReferenceFinish notes when the reference player finishes a VS race.
func trackReferenceFinish(m *mirrorSource, aid byte, pkt *RacePacket, now time.Time) {
	if pkt.RaceInfo == nil || pkt.RaceMode == nil || pkt.RaceMode.VS == nil {
		return
	}
	vs := pkt.RaceMode.VS
	ft := vs.FinishTimes[0]
	finished := vs.LocalPlayerCount >= 1 && (ft.Minutes != 0 || ft.Seconds != 0 || ft.Milliseconds != 0)

	// A new race (or not finished yet) clears the previous finish.
	if !finished || !pkt.IsCountdownStarted() {
		m.finishedAt = time.Time{}
		return
	}
	if !m.finishedAt.IsZero() {
		return
	}

	m.finishedAt = now
	m.finishTime = ft
	m.finishBitShift = 0

	// Find the reference's own bit in the finished field. It's the only one set at the
	// moment they finish, since bots only finish after them.
	id := playerIdOf(m.records[common.RaceInfo], aid)
	for bit := range raceModePlayerBits {
		if vs.FinishedPlayers>>(raceModePlayerBits-1-bit)&1 == 1 && id >= 0 {
			m.finishBitShift = bit - id
			break
		}
	}
}

// botFinish returns a bot's finishing time and finished-field bit once its replay of the
// reference has crossed the line.
func botFinish(bot *Aid, m *mirrorSource, now time.Time) (records.FinishTime, int, bool) {
	if m == nil || m.finishedAt.IsZero() || now.Before(m.finishedAt.Add(bot.bot.delay)) {
		return records.FinishTime{}, -1, false
	}
	ft := addMilliseconds(m.finishTime, int(bot.bot.delay.Milliseconds()))
	bit := -1
	if id := playerIdOf(m.records[common.RaceInfo], bot.aid); id >= 0 {
		bit = id + m.finishBitShift
	}
	return ft, bit, true
}

func addMilliseconds(t records.FinishTime, ms int) records.FinishTime {
	total := (int(t.Minutes)*60+int(t.Seconds))*1000 + int(t.Milliseconds) + ms
	return records.FinishTime{
		Minutes:      byte(min(total/60000, 63)),
		Seconds:      byte(total / 1000 % 60),
		Milliseconds: uint16(total % 1000),
	}
}

func packFinishTime(t records.FinishTime) uint32 {
	return uint32(t.Minutes)<<16 | uint32(t.Seconds)<<10 | uint32(t.Milliseconds)
}

// raceInfoPlayerCount counts the racers in a RaceInfo's player id -> aid map (0xff: empty).
func raceInfoPlayerCount(raceInfo []byte) int {
	if len(raceInfo) < 0x24 {
		return 0
	}
	n := 0
	for _, a := range raceInfo[0x18:0x24] {
		if a != 0xff {
			n++
		}
	}
	return n
}
